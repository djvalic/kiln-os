#!/usr/bin/env python3
"""Build the recovery UI's string table (src/i18n_ids.h, src/i18n_tab.c).

usage: gen_i18n.py [--out DIR]     (default DIR: ../src next to this file)

Source: en.txt (the key list: id, TAB, English text) and one file per
language code (zh.txt, ja.txt, ...). Each language file has the same ids
with the translation after the TAB; an empty text means "show English".
Rules checked here:
  - ids are lower case words; every id is in en.txt and each is in en.txt once
  - en.txt has a text for every id
  - a translation has the same %-placeholders in the same order as English
  - "\\n" in a text is a line break; "%%" is a percent sign
Run it after editing any file here; fonts/gen_fonts.py reads the same
files to choose the glyphs.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")

# Codes of the setup wizard's language picker; index = enum value.
# en is first: it is the fallback for every other language.
LANGS = ["en", "zh", "ja", "de", "es", "it", "ru", "pt", "ko", "tr"]
ID_RE = re.compile(r"^[a-z][a-z0-9_]*$")
SPEC_RE = re.compile(r"%[-+ #0-9.]*[lhz]*[a-zA-Z]")


class Error(Exception):
    pass


def load(path):
    """[(id, text)] in file order; text has real newlines."""
    out = []
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            if "\t" not in line:
                raise Error("%s:%d: expected id<TAB>text" % (path, n))
            key, text = line.split("\t", 1)
            if not ID_RE.match(key):
                raise Error("%s:%d: bad id %r" % (path, n, key))
            out.append((key, text.replace("\\n", "\n")))
    return out


def specs(text):
    return SPEC_RE.findall(text.replace("%%", ""))


def collect(here=HERE):
    """({code: {id: text}}, [ids in en.txt order]); checks everything above."""
    en = load(os.path.join(here, "en.txt"))
    ids = [k for k, _ in en]
    if len(set(ids)) != len(ids):
        raise Error("en.txt: duplicate id")
    english = dict(en)
    for k, t in en:
        if not t:
            raise Error("en.txt: %s has no English text" % k)
    tables = {"en": english}
    for code in LANGS[1:]:
        path = os.path.join(here, code + ".txt")
        if not os.path.exists(path):
            raise Error("missing %s" % path)
        tab = {}
        for k, t in load(path):
            if k not in english:
                raise Error("%s.txt: unknown id %s" % (code, k))
            if k in tab:
                raise Error("%s.txt: duplicate id %s" % (code, k))
            if t and specs(t) != specs(english[k]):
                raise Error("%s.txt: %s placeholders %s differ from English %s"
                            % (code, k, specs(t), specs(english[k])))
            tab[k] = t
        tables[code] = tab
    return tables, ids


def c_str(s):
    """C string literal; non-ASCII bytes as octal escapes (never ambiguous)."""
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch == "\n":
            out.append("\\n")
        elif ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def render(tables, ids):
    enum_names = ["RS_" + k.upper() for k in ids]
    lines = ["/* Generated by recovery-ui/i18n/gen_i18n.py from the text files there. Do not edit. */",
             "#ifndef RUI_I18N_IDS_H", "#define RUI_I18N_IDS_H", "",
             "enum rui_str {"]
    lines += ["\t%s," % n for n in enum_names]
    lines += ["\tRS__COUNT", "};", "", "typedef enum {"]
    lines += ["\tLANG_%s," % c.upper() for c in LANGS]
    lines += ["\tLANG__COUNT", "} rui_lang;", "",
              "extern const char *const rui_lang_code[LANG__COUNT];",
              "extern const char *const rui_i18n_text[LANG__COUNT][RS__COUNT];", "",
              "#endif", ""]
    header = "\n".join(lines)

    tab = ["/* Generated by recovery-ui/i18n/gen_i18n.py from the text files there. Do not edit. */",
           '#include "i18n_ids.h"', "",
           "const char *const rui_lang_code[LANG__COUNT] = {"]
    tab += ['\t"%s",' % c for c in LANGS]
    tab += ["};", "", "/* Empty entries fall back to English (LANG_EN) at run time */",
            "const char *const rui_i18n_text[LANG__COUNT][RS__COUNT] = {"]
    for code in LANGS:
        tab.append("\t[LANG_%s] = {" % code.upper())
        for k, n in zip(ids, enum_names):
            t = tables[code].get(k, "")
            if t:
                tab.append("\t\t[%s] = %s," % (n, c_str(t)))
        tab.append("\t},")
    tab += ["};", ""]
    return header, "\n".join(tab)


def main(argv):
    out = SRC
    if len(argv) == 2 and argv[0] == "--out":
        out = argv[1]
    elif argv:
        print(__doc__)
        return 2
    try:
        tables, ids = collect()
    except Error as e:
        print("gen_i18n: " + str(e), file=sys.stderr)
        return 1
    header, tab = render(tables, ids)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "i18n_ids.h"), "w", encoding="utf-8") as f:
        f.write(header)
    with open(os.path.join(out, "i18n_tab.c"), "w", encoding="utf-8") as f:
        f.write(tab)
    translated = {c: sum(1 for v in tables[c].values() if v) for c in LANGS}
    print("gen_i18n: %d strings; translated per language: %s"
          % (len(ids), " ".join("%s=%d" % kv for kv in translated.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
